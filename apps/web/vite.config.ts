import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineConfig, type Plugin } from "vite";

const webRoot = fileURLToPath(new URL(".", import.meta.url));
const publicFiles = [
  "manifest.webmanifest",
  "icon.svg",
  "apple-touch-icon.png",
  "icon-192.png",
  "icon-512.png",
  "engine-worklet.js",
  "synth-core.js",
  "vehicle-combustion.js",
  "electric-synth.js"
];

/**
 * Emitted only during production builds. The offline worker is scoped to
 * the installed app directory, including GitHub Pages subpaths.
 * Hashed Vite assets and all original procedural synth modules are precached
 * as one version-consistent app shell. No external/user data is cached.
 */
function offlineShell(): Plugin {
  return {
    name: "enginesoundlab-pwa-shell",
    apply: "build",
    generateBundle(_options, bundle) {
      const hash = createHash("sha256");
      const generated = Object.entries(bundle)
        .filter(([path]) => /\.(?:js|css)$/.test(path))
        .sort(([a], [b]) => a.localeCompare(b));
      for (const [path, item] of generated) {
        hash.update(path);
        hash.update(item.type === "chunk" ? item.code : item.source);
      }
      for (const path of publicFiles) {
        hash.update(path);
        hash.update(readFileSync(fileURLToPath(new URL("public/" + path, import.meta.url))));
      }
      const cache = "enginesoundlab-shell-" + hash.digest("hex").slice(0, 16);
      const precache = [
        "./",
        "./index.html",
        ...publicFiles.map(path => "./" + path),
        ...generated.map(([path]) => "./" + path)
      ];
      const source = [
        "// Generated by apps/web/vite.config.ts. Never cache user data.",
        "const CACHE_NAME = " + JSON.stringify(cache) + ";",
        "const PRECACHE = " + JSON.stringify(precache) + ";",
        "const CACHE_PREFIX = 'enginesoundlab-shell-';",
        "self.addEventListener('install', event => {",
        "  event.waitUntil(caches.open(CACHE_NAME).then(cache =>",
        "    cache.addAll(PRECACHE.map(path => new URL(path, self.registration.scope)))));",
        "});",
        "self.addEventListener('activate', event => {",
        "  event.waitUntil(caches.keys().then(keys => Promise.all(",
        "    keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)",
        "      .map(key => caches.delete(key))",
        "  )));",
        "});",
        "self.addEventListener('fetch', event => {",
        "  const request = event.request;",
        "  if (request.method !== 'GET') return;",
        "  const url = new URL(request.url);",
        "  const scope = new URL(self.registration.scope);",
        "  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;",
        "  if (request.mode === 'navigate') {",
        "    event.respondWith(caches.open(CACHE_NAME).then(cache =>",
        "      cache.match(new URL('./index.html', scope)).then(response => response || fetch(request))",
        "    ));",
        "    return;",
        "  }",
        "  event.respondWith(caches.match(request).then(response => response || fetch(request)));",
        "});",
        ""
      ].join("\n");
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    }
  };
}

export default defineConfig({
  root: webRoot,
  base: "./",
  plugins: [offlineShell()],
  build: { outDir: "../../dist/web", emptyOutDir: true }
});
